#!/usr/bin/env python3
"""Generate the side-ordered Lean coefficient certificates from witness JSONL."""

from __future__ import annotations

import argparse
import json
from math import isqrt
from pathlib import Path


PROJECT = Path(__file__).resolve().parents[1]
WEIGHT_LIMIT = 6400
COLUMN_COUNT = isqrt(WEIGHT_LIMIT)
LITERALS_PER_LIST = 128
GENERATED = "/- Generated by review/generate_step05_coefficients.py. -/\n"
NAMESPACE = "DurfeeCCS.Step05"


def read_columns(source: Path) -> list[list[int]]:
    columns = [[0] for _ in range(COLUMN_COUNT)]
    with source.open(encoding="utf-8-sig") as stream:
        expected = 1
        for line in stream:
            weight, coefficients, _ = json.loads(line)
            if weight != expected or expected > WEIGHT_LIMIT:
                raise ValueError(f"expected weight {expected}, got {weight}")
            if len(coefficients) != isqrt(weight) or any(
                type(value) is not int or value < 0 for value in coefficients
            ):
                raise ValueError(f"invalid coefficient row for weight {weight}")
            for side, column in enumerate(columns, start=1):
                column.append(coefficients[side - 1] if side <= len(coefficients) else 0)
            expected += 1
    if expected != WEIGHT_LIMIT + 1:
        raise ValueError(f"witness file ended before weight {WEIGHT_LIMIT}")
    return columns


def write_text(path: Path, text: str) -> None:
    data = text.encode("utf-8")
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def module_header(imports: list[str], *, options: bool = False) -> str:
    output = GENERATED + "module\n\n" + "".join(f"public import {name}\n" for name in imports)
    if options:
        output += "\nset_option maxRecDepth 120000\nset_option maxHeartbeats 0\n"
    return output + f"\n@[expose] public section\nnamespace {NAMESPACE}\n\n"


def column_expression(values: list[int]) -> str:
    groups = []
    for start in range(0, len(values), LITERALS_PER_LIST):
        segment = values[start : start + LITERALS_PER_LIST]
        if not any(segment):
            groups.append(f"  List.replicate {len(segment)} 0")
        else:
            groups.append("  [" + ", ".join(map(str, segment)) + "]")
    return "List.flatten [\n" + ",\n".join(groups) + "\n]"


def generate(source: Path, destination: Path, columns_per_module: int) -> None:
    columns = read_columns(source)
    destination.mkdir(parents=True, exist_ok=True)
    checks = []
    previous_data = None
    for offset in range(0, COLUMN_COUNT, columns_per_module):
        group = offset // columns_per_module + 1
        data_name = f"CoeffData{group:02d}"
        check_name = f"CoeffCheck{group:02d}"
        data_import = f"{NAMESPACE}.{data_name}"
        data = module_header([], options=True)
        checks.append(f"{NAMESPACE}.{check_name}")
        imports = [data_import] if previous_data is None else [previous_data, data_import]
        check = module_header(["DurfeeCCS.CoefficientCertificate", *imports], options=True)
        for index, column in enumerate(columns[offset : offset + columns_per_module], offset + 1):
            data += (f"noncomputable def coefficientColumn{index} : List Int :=\n"
                     f"{column_expression(column)}\n\n")
            previous = (f"(baseCoefficientRow {WEIGHT_LIMIT})" if index == 1
                        else f"coefficientColumn{index - 1}")
            check += (f"theorem coefficientColumn{index}_checked :\n"
                      f"    verifyPairRow {index - 1} {previous} coefficientColumn{index} = true := by\n"
                      "  decide +kernel\n\n")
        write_text(destination / f"{data_name}.lean", data + f"end {NAMESPACE}\n")
        write_text(destination / f"{check_name}.lean", check + f"end {NAMESPACE}\n")
        previous_data = data_import

    output = module_header(checks, options=True)
    for index in range(1, COLUMN_COUNT + 1):
        prev_spec = (f"(baseCoefficientRow_spec {WEIGHT_LIMIT})" if index == 1
                     else f"coefficientColumn{index - 1}_spec")
        prev_length = "rfl" if index == 1 else f"coefficientColumn{index - 1}_length"
        output += (f"theorem coefficientColumn{index}_spec : CoefficientRowSpec {index} coefficientColumn{index} :=\n"
                   f"  verifyPairRow_sound {prev_spec} coefficientColumn{index}_checked\n\n"
                   f"theorem coefficientColumn{index}_length : coefficientColumn{index}.length = {WEIGHT_LIMIT + 1} :=\n"
                   f"  (verifyPairRow_length coefficientColumn{index}_checked).trans {prev_length}\n\n")
    columns_names = [f"coefficientColumn{index}" for index in range(1, COLUMN_COUNT + 1)]
    output += ("noncomputable def coefficientColumns : List (List ℤ) := [\n  "
               + ",\n  ".join(columns_names) + "\n]\n\n")
    output += (f"theorem coefficientColumns_length : ∀ c ∈ coefficientColumns, c.length = {WEIGHT_LIMIT + 1} := by\n"
               "  simp [coefficientColumns, List.forall_mem_cons,\n    "
               + ",\n    ".join(f"{name}_length" for name in columns_names) + "]\n\n")
    output += ("theorem coefficientColumns_spec (j : ℕ) (hj : j < coefficientColumns.length) :\n"
               "    CoefficientRowSpec (j + 1) coefficientColumns[j] := by\n"
               "  have hs : CoefficientColumnsSpec 1 coefficientColumns :=\n    "
               + "\n    ".join(f"coefficientColumnsSpec_cons {name}_spec (" for name in columns_names)
               + f"coefficientColumnsSpec_nil {COLUMN_COUNT + 1}" + ")" * COLUMN_COUNT + "\n"
               "  simpa [Nat.add_comm] using hs j hj\n\n")
    write_text(destination / "Columns.lean", output + f"end {NAMESPACE}\n")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=PROJECT / "review/step05-witnesses.jsonl")
    parser.add_argument("--destination", type=Path, default=PROJECT / "DurfeeCCS/Step05")
    parser.add_argument("--columns-per-module", type=int, default=8)
    args = parser.parse_args()
    if args.columns_per_module < 1:
        parser.error("--columns-per-module must be positive")
    generate(args.source, args.destination, args.columns_per_module)


if __name__ == "__main__":
    main()
