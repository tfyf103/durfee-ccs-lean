"""Render deterministic Lean sign-check and coefficient-link shards from the raw certificate."""

import argparse
import json
from pathlib import Path


LIMIT = 6400
SHARD_SIZE = 64
PROOF_BLOCK_SIZE = 4
NAMESPACE = 'DurfeeCCS.Step05'
HEADER = '-- Generated by review/generate_step05_shards.py.\nmodule\n\n'
OPTIONS = 'set_option maxHeartbeats 0\nset_option maxRecDepth 120000\n\n'


def store_module(directory, name, imports, body):
    declarations = ''.join(f'public import {module}\n' for module in imports)
    text = (f'{HEADER}{declarations}\n{OPTIONS}@[expose] public section\n\n'
            f'namespace {NAMESPACE}\n\n{body}\n\nend {NAMESPACE}\n')
    path = directory / f'{name}.lean'
    data = text.encode('utf-8')
    if not path.exists() or path.read_bytes() != data:
        path.write_bytes(data)


def list_literal(values):
    return '[' + ', '.join(str(value) for value in values) + ']'


def render_row(row):
    _, coefficients, points = row
    dyadics = ', '.join(f'({numerator}, {exponent})' for numerator, exponent in points)
    return f'  ({list_literal(coefficients)}, [{dyadics}])'


def render_sign_shard(directory, tag, rows):
    fragments = []
    checks = []
    declarations = []
    for offset in range(0, len(rows), PROOF_BLOCK_SIZE):
        block = rows[offset:offset + PROOF_BLOCK_SIZE]
        suffix = f'{tag}_{offset // PROOF_BLOCK_SIZE:02d}'
        fragments.append(f'points{suffix}')
        checks.append(f'signs{suffix}')
        row_data = ',\n'.join(map(render_row, block))
        declarations.append(f'''noncomputable def points{suffix} : List FiniteWitnessRow := [
{row_data}
]

private theorem signs{suffix} : points{suffix}.all checkFiniteWitnessRow = true := by
  decide +kernel''')
    joined = ' ++ '.join(fragments)
    checked = ', '.join(checks)
    body = '\n\n'.join(declarations) + f'''

noncomputable def rows{tag} : List FiniteWitnessRow :=
  {joined}

theorem rows{tag}_length : rows{tag}.length = {len(rows)} := rfl

theorem signs{tag} : checkFiniteWitnessBlock rows{tag} = true := by
  simp only [checkFiniteWitnessBlock, rows{tag}, List.all_append, {checked}, Bool.and_self]'''
    store_module(directory, f'Shard{tag}', ['DurfeeCCS.FiniteCertificateSoundness'], body)


def render_range_shard(directory, tag, rows):
    low = rows[0][0]
    high = rows[-1][0] + 1
    bound_tactic = (f'rw [rows{tag}_length]' if high == LIMIT + 1
                    else f'rw [rows{tag}_length]; decide')
    body = f'''theorem coefficients{tag} :
    checkCoefficientBlock {low} (coefficientSlices coefficientColumns {low} rows{tag}.length)
      (rows{tag}.map Prod.fst) = true := by decide +kernel

theorem coverage{tag} (n : ℕ) (hlo : {low} ≤ n) (hhi : n < {high}) :
    HasDyadicFiniteWitnesses n := by
  exact finiteWitnessBlock_of_checks coefficientColumns_length coefficientColumns_spec
    (by {bound_tactic}) coefficients{tag} signs{tag} n hlo
    (by simpa only [rows{tag}_length] using hhi)'''
    store_module(directory, f'Range{tag}', ['DurfeeCCS.FiniteCertificates',
                 f'{NAMESPACE}.Columns', f'{NAMESPACE}.Shard{tag}'], body)


def join_coverage(tags):
    if len(tags) == 1:
        return f'coverage{tags[0]}'
    split = len(tags) // 2
    return f'(joinCoverage {join_coverage(tags[:split])} {join_coverage(tags[split:])})'


def render_total(directory, tags):
    body = f'''private theorem joinCoverage {{lo mid hi : ℕ}}
    (left : ∀ n, lo ≤ n → n < mid → HasDyadicFiniteWitnesses n)
    (right : ∀ n, mid ≤ n → n < hi → HasDyadicFiniteWitnesses n) :
    ∀ n, lo ≤ n → n < hi → HasDyadicFiniteWitnesses n := by
  intro n hlo hhi
  by_cases hn : n < mid
  · exact left n hlo hn
  · exact right n (Nat.le_of_not_gt hn) hhi

/-- The positive dyadic interior witnesses of (77) exist for every required finite size. -/
theorem finiteDyadicWitnesses_complete (n : ℕ) (hn : 9 ≤ n) (hmax : n ≤ 6400) :
    HasDyadicFiniteWitnesses n :=
  {join_coverage(tags)} n (by omega) (by omega)

theorem finiteWitnesses_complete (n : ℕ) (hn : 9 ≤ n) (hmax : n ≤ 6400) :
    HasFiniteWitnesses n :=
  (finiteDyadicWitnesses_complete n hn hmax).toFinite

/-- The finite-size conclusion, with real and complex root exhaustion and simplicity. -/
theorem finiteDurfeeRoots (n : ℕ) (hn : 1 ≤ n) (hmax : n ≤ 6400) : HasDurfeeRoots n := by
  by_cases hsmall : n ≤ 8
  · exact hasDurfeeRoots_of_small hn hsmall
  · exact hasDurfeeRoots_of_finiteWitnesses hn
      (Nat.le_sqrt.mpr (by omega)) (finiteWitnesses_complete n (by omega) hmax)

/-- A direct complex formulation for the polynomial defined in the project. -/
theorem finiteDurfeeComplexRoots (n : ℕ) (hn : 1 ≤ n) (hmax : n ≤ 6400) :
    ∃ r : Fin (n.sqrt - 1) ↪ ℝ, (∀ i, r i < 0) ∧
      (durfeePolynomialComplex n).roots.card = n.sqrt ∧
      (∀ z : ℂ, (durfeePolynomialComplex n).IsRoot z ↔ z = 0 ∨ ∃ i, z = (r i : ℂ)) ∧
      (∀ z : ℂ, (durfeePolynomialComplex n).IsRoot z →
        Polynomial.rootMultiplicity z (durfeePolynomialComplex n) = 1) := by
  obtain ⟨r, hneg, hroot⟩ := finiteDurfeeRoots n hn hmax
  rw [durfeePolynomialComplex_eq_map_real]
  refine ⟨r, hneg, ?_, hroot.complex_root_iff, hroot.complex_simple⟩
  rw [hroot.complex_card, Nat.sub_add_cancel (Nat.sqrt_pos.mpr hn)]'''
    store_module(directory, 'All', [f'{NAMESPACE}.Range{tag}' for tag in tags], body)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('data', type=Path)
    parser.add_argument('--output', type=Path, default=Path('DurfeeCCS/Step05'))
    args = parser.parse_args()
    with args.data.open(encoding='utf-8') as source:
        rows = [json.loads(line) for line in source]
    if [row[0] for row in rows] != list(range(1, LIMIT + 1)):
        raise ValueError(f'Expected the weights 1 through {LIMIT} in order')
    args.output.mkdir(parents=True, exist_ok=True)
    tags = []
    for offset in range(0, LIMIT, SHARD_SIZE):
        tag = f'{offset // SHARD_SIZE:03d}'
        block = rows[offset:offset + SHARD_SIZE]
        tags.append(tag)
        render_sign_shard(args.output, tag, block)
        render_range_shard(args.output, tag, block)
    render_total(args.output, tags)


if __name__ == '__main__':
    main()
